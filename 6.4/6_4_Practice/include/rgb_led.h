#pragma once
// Вбудований RGB-світлодіод ESP32-S3-DevKitC-1 (спільний для кроків 2 і 3).
//
// Це не звичайний LED, а адресний WS2812: всередині маленький контролер, який приймає
// колір послідовним протоколом (24 біти GRB, імпульси ~0,4 / 0,8 мкс). Тому gpio_set_level()
// тут не працює. Імпульси формує периферія RMT через офіційний компонент espressif/led_strip.
// Аналогія: звичайний LED - лампочка з вимикачем, WS2812 - лампочка, якій кажуть колір по телефону.
//
// Викликати лише з однієї задачі (у практиці - fsm_task): драйвер не захищений mutex-ом.

#include <stdint.h>

typedef struct {
  uint8_t r, g, b; // 0-255; на платі світлодіод дуже яскравий, вистачає 10-40
} rgb_t;

#define RGB_OFF ((rgb_t){0, 0, 0})

void rgb_led_init(void);
void rgb_led_set(rgb_t color);
